#!/usr/bin/env node
/**
 * Build the publishable Scaleproof CLI bundle.
 *
 * Purpose: bundle only `src/cli/entry.ts` into `cli/dist/scaleproof.mjs` with
 * esbuild, injecting the `cli/package.json` version and the synthetic demo
 * fixture at build time. The published bundle therefore reads no manifest and
 * no fixture directory at runtime, so `--demo` works from any directory while
 * the package keeps its four-file allowlist.
 *
 * Prerequisites: `npm ci` (esbuild is a devDependency of the root package).
 *
 * Usage:
 *   node ./scripts/build-cli.mjs
 *   npm run build:cli
 *
 * The build fails loudly on any esbuild error and exits non-zero.
 */

import { readdir, readFile, mkdir } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const entryPoint = path.join(repositoryRoot, "src/cli/entry.ts");
const outputFile = path.join(repositoryRoot, "cli/dist/scaleproof.mjs");
const demoFixtureRoot = path.join(repositoryRoot, "fixtures/scaleproof-demo");

// The fixture is synthetic scanner input, not a dependency. Cap it so an
// accidental addition cannot silently inflate the published bundle.
const MAX_FIXTURE_FILES = 64;
const MAX_FIXTURE_BYTES = 512 * 1024;

/**
 * Read the synthetic demo repository into a sorted relative-path map. Sorting
 * keeps the injected blob byte-stable across builds.
 */
async function readDemoFixture(root) {
  const files = [];
  async function walk(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    for (const entry of entries.sort((left, right) =>
      left.name.localeCompare(right.name),
    )) {
      const target = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        await walk(target);
      } else if (entry.isFile()) {
        files.push(target);
      }
    }
  }
  await walk(root);

  if (files.length === 0) {
    throw new Error(`No demo fixture files were found under ${path.relative(repositoryRoot, root)}.`);
  }
  if (files.length > MAX_FIXTURE_FILES) {
    throw new Error(
      `The demo fixture has ${files.length} files; the bundle allows ${MAX_FIXTURE_FILES}.`,
    );
  }

  const fixture = {};
  let bytes = 0;
  for (const file of files) {
    const buffer = await readFile(file);
    if (buffer.includes(0)) {
      throw new Error("The demo fixture must contain UTF-8 text files only.");
    }
    bytes += buffer.byteLength;
    if (bytes > MAX_FIXTURE_BYTES) {
      throw new Error(
        `The demo fixture exceeds the ${MAX_FIXTURE_BYTES}-byte bundle budget.`,
      );
    }
    const relativePath = path
      .relative(root, file)
      .split(path.sep)
      .join("/");
    fixture[relativePath] = buffer.toString("utf8");
  }
  return { fixture, bytes };
}

function log(message) {
  process.stdout.write(`build:cli ${message}\n`);
}

async function main() {
  log("=== started ===");

  const manifest = JSON.parse(
    await readFile(path.join(repositoryRoot, "cli/package.json"), "utf8"),
  );
  if (typeof manifest.version !== "string" || !manifest.version) {
    throw new Error("cli/package.json is missing a version.");
  }

  const demo = await readDemoFixture(demoFixtureRoot);
  log(
    `embedded demo fixture: ${Object.keys(demo.fixture).length} files, ${demo.bytes} bytes`,
  );

  await mkdir(path.dirname(outputFile), { recursive: true });

  const result = await build({
    entryPoints: [entryPoint],
    outfile: outputFile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    // Node 22.11 is the executable baseline; see the root package engines.
    minify: false,
    sourcemap: false,
    treeShaking: true,
    legalComments: "none",
    logLevel: "warning",
    metafile: true,
    define: {
      __SCALEPROOF_CLI_VERSION__: JSON.stringify(manifest.version),
      __SCALEPROOF_DEMO_FIXTURE__: JSON.stringify(JSON.stringify(demo.fixture)),
      "process.env.NODE_ENV": JSON.stringify("production"),
    },
    // Keep the bundle self-contained. Externalizing a dependency would force
    // it into cli/package.json and widen the install surface.
    external: [],
    banner: {
      js: [
        "// Scaleproof CLI bundle. Generated by scripts/build-cli.mjs; do not edit.",
        "import { createRequire as __scaleproofCreateRequire } from 'node:module';",
        "const require = __scaleproofCreateRequire(import.meta.url);",
      ].join("\n"),
    },
    alias: {
      "@": path.join(repositoryRoot, "src"),
    },
  });

  const bytes = Object.values(result.metafile.outputs).reduce(
    (total, output) => total + output.bytes,
    0,
  );
  log(`version ${manifest.version}`);
  log(`bundled cli/dist/scaleproof.mjs (${bytes} bytes)`);
  log("=== done ===");
}

main().catch((error) => {
  process.stderr.write(
    `build:cli failed: ${error instanceof Error ? error.message : String(error)}\n`,
  );
  process.exit(1);
});

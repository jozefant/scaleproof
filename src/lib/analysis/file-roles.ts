import * as signals from "./signals";
import { isServerSurfaceFile } from "./static-frontend";
import type { EvidenceReference } from "./types";

/**
 * Execution-context file roles.
 *
 * A repository file can carry perfectly good evidence and still say nothing
 * about production execution. A fixed credential inside `src/test/resources`
 * is a test property, not a leaked production key. A `for` loop around a
 * repository lookup inside a one-off import script is a batch job, not a
 * request-path N+1. A generated component-library primitive is vendored code,
 * not the founder's request handler.
 *
 * This module owns one shared classification so every control asks the same
 * question and gets the same answer:
 *
 * | Role | Meaning |
 * | --- | --- |
 * | `production` | Application source or deployment configuration that can run in production |
 * | `test` | Unit, integration, contract, or end-to-end test code and its explicitly non-production configuration |
 * | `fixture` | Fixtures, examples, samples, and demo data |
 * | `generated` | Generated, vendored, or dependency-managed artifacts |
 * | `documentation` | Documentation, licences, and change logs |
 * | `tooling` | Offline or administrative tooling: scripts, migrations, seeds, CI definitions |
 *
 * The role is **internal**. It scopes applicability and severity inside the
 * deterministic engine and is asserted in tests. It is never added to
 * `CheckResult`, never rendered into the public report, and never sent to a
 * model. Public evidence stays exactly what it was: a safe path and a
 * deterministic summary.
 *
 * Nothing here retains source text. Callers receive a role, a boolean, or a
 * filtered list of files they already hold.
 */
export type FileRole =
  | "production"
  | "test"
  | "fixture"
  | "generated"
  | "documentation"
  | "tooling";

/**
 * Roles whose evidence cannot, on its own, establish that code runs in
 * production. Evidence from these roles is still reported; it is only barred
 * from asserting a production execution fact.
 */
export const NON_PRODUCTION_FILE_ROLES: ReadonlySet<FileRole> = new Set<FileRole>([
  "test",
  "fixture",
  "generated",
  "documentation",
  "tooling",
]);

/* ---------------------------------------------------------------------- */
/* Generated and vendored artifacts                                        */
/* ---------------------------------------------------------------------- */

const GENERATED_DIRECTORY =
  /(^|\/)(?:node_modules|bower_components|jspm_packages|vendor|third[-_]?party|\.yarn|\.pnp|\.next|\.nuxt|\.svelte-kit|\.turbo|\.angular|\.gradle|target|__generated__|generated|codegen|__pycache__)(\/|$)/i;
const DEPENDENCY_LOCK_FILE =
  /(^|\/)(?:package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|composer\.lock|gemfile\.lock|poetry\.lock|pipfile\.lock|cargo\.lock|go\.sum|packages\.lock\.json)$/i;
const GENERATED_FILE =
  /\.(?:min\.[cm]?[jt]sx?|min\.css|bundle\.[cm]?[jt]s|generated\.[a-z0-9]+|g\.dart|pb\.go|pb\.[cm]?ts)$|_pb2(?:_grpc)?\.py$/i;
const TYPE_DECLARATION_FILE = /\.d\.[cm]?ts$/i;
/**
 * A generated-artifact banner. Only the file header is inspected: the phrase
 * "do not edit" appears in ordinary prose deep inside real source files.
 */
const GENERATED_BANNER =
  /^[^\S\r\n]*(?:\/\/|#|\/\*|\*|--|<!--|;)?[^\S\r\n]*(?:@generated\b|code generated by\b|this file (?:is|was) (?:auto[- ]?)?generated\b|auto[- ]?generated\b|do not edit\b)/im;
const GENERATED_BANNER_WINDOW = 800;
/**
 * Generated user-interface primitives. Component-library generators copy their
 * primitives into the repository verbatim, so the directory alone is not
 * enough: the file must also carry a generator's own dependency signature.
 */
const UI_PRIMITIVE_PATH = /(^|\/)components\/ui\/[^/]+\.[cm]?[jt]sx?$/i;
const UI_PRIMITIVE_CONTENT =
  /@radix-ui\/|class-variance-authority|\bshadcn\b|@headlessui\/|cmdk|vaul/i;

/* ---------------------------------------------------------------------- */
/* Tests                                                                   */
/* ---------------------------------------------------------------------- */

const TEST_DIRECTORY =
  /(^|\/)(?:tests?|__tests__|__mocks__|specs?|testing|test[-_]?data|testdata|mocks|stubs|e2e|cypress|playwright|integration[-_]?tests?|androidtest|integrationtest)(\/|$)/i;
const TEST_FILE = [
  /\.(?:spec|test|e2e|steps|cy)\.[cm]?[jt]sx?$/i,
  /(^|\/)test_[^/]+\.py$/i,
  /_test\.py$/i,
  /_test\.go$/i,
  /(^|\/)conftest\.py$/i,
  // JVM and .NET test classes are recognized by their build-tool source set
  // (`src/test/...`) and by their framework annotations, never by a filename
  // suffix: `Latest.java` also ends in "test" once a path is lower-cased.
  /[^/]*_spec\.rb$/i,
  /(^|\/)(?:jest|vitest|karma|cypress|playwright|codecept|wdio)\.config\.[cm]?[jt]s$/i,
  /(^|\/)(?:jest|vitest)\.setup\.[cm]?[jt]sx?$/i,
  /(^|\/)setuptests\.[cm]?[jt]sx?$/i,
];
/**
 * Configuration that names itself non-production. A Spring `application-test`
 * profile, a `.env.test`, and a `compose.test.yml` are declarations by the
 * author that the values inside are not the deployed ones.
 */
const NON_PRODUCTION_CONFIGURATION = [
  /(^|\/)application-(?:test|tests|it|integrationtest|ci|local)\.(?:properties|ya?ml|yml|conf|json)$/i,
  /(^|\/)\.env\.(?:test|testing|example|sample|template|dist)$/i,
  /(^|\/)(?:docker-)?compose[.-](?:test|tests|ci|e2e|dev)\.ya?ml$/i,
  /(^|\/)[^/]*\.(?:test|spec)\.(?:properties|ya?ml|json|toml|conf|ini|xml)$/i,
  /(^|\/)[^/]*\.(?:example|sample|template|dist)$/i,
];
/**
 * Test frameworks announce themselves. These signals are used only when the
 * path is otherwise ambiguous, and each one is an import or annotation that
 * does not appear in production code.
 */
const TEST_CONTENT = [
  /@(?:Test|SpringBootTest|DataJpaTest|WebMvcTest|ParameterizedTest|QuarkusTest|MicronautTest)\b/,
  /\bimport\s+(?:static\s+)?org\.junit\b/,
  /\bimport\s+(?:static\s+)?org\.(?:mockito|assertj|testng)\b/,
  /^\s*import\s+pytest\b/m,
  /^\s*(?:from|import)\s+unittest\b/m,
  /\bfrom\s+["']vitest["']|\bfrom\s+["']@jest\/globals["']|\bfrom\s+["']@playwright\/test["']/,
];
const TEST_SUITE_CONTENT = /\bdescribe\s*\(\s*['"`]/;
const TEST_CASE_CONTENT = /\b(?:it|test)\s*\(\s*['"`]/;

/* ---------------------------------------------------------------------- */
/* Fixtures, demos, and examples                                           */
/* ---------------------------------------------------------------------- */

const FIXTURE_DIRECTORY =
  /(^|\/)(?:fixtures?|__fixtures__|examples?|samples?|demos?|sample[-_]?data|seed[-_]?data|dummy[-_]?data|storybook|\.storybook)(\/|$)/i;
const FIXTURE_FILE = [
  /\.(?:fixture|fixtures|mock|mocks|stub|stories)\.[cm]?[jt]sx?$/i,
  /(^|\/)[^/]*\.stories\.(?:mdx|[cm]?[jt]sx?)$/i,
];

/* ---------------------------------------------------------------------- */
/* Documentation                                                           */
/* ---------------------------------------------------------------------- */

const DOCUMENTATION_DIRECTORY =
  /(^|\/)(?:docs?|documentation|adrs?|architecture-decisions|decision-records|\.github\/issue_template|wiki)(\/|$)/i;
const DOCUMENTATION_FILE = [
  /\.(?:md|mdx|markdown|rst|adoc|asciidoc|txt)$/i,
  /(^|\/)(?:license|licence|notice|copying|changelog|authors|contributors|codeowners)(?:\.[a-z]+)?$/i,
];

/* ---------------------------------------------------------------------- */
/* Offline and administrative tooling                                      */
/* ---------------------------------------------------------------------- */

const TOOLING_DIRECTORY =
  /(^|\/)(?:scripts?|tools?|tooling|bin|automation|\.husky|\.github|\.circleci|\.gitlab|\.buildkite|\.azuredevops|migrations?|db[-_]?migrations?|liquibase|flyway|seeds?|seeders?|prisma\/migrations)(\/|$)/i;
const TOOLING_FILE = [
  /(^|\/)(?:seed|seeds|seeder|backfill|migrate|import[-_][a-z0-9-]+|[a-z0-9-]+[-_]importer)\.[cm]?[jt]sx?$/i,
  /(^|\/)(?:makefile|justfile|rakefile|gulpfile\.[cm]?[jt]s|gruntfile\.[cm]?[jt]s)$/i,
  /(^|\/)\.gitlab-ci\.ya?ml$/i,
  /(^|\/)(?:azure-pipelines|appveyor|bitbucket-pipelines)\.ya?ml$/i,
  /(^|\/)v?\d+[_-][a-z0-9_-]*\.sql$/i,
];

/**
 * Continuous-integration definitions. They are offline tooling for execution
 * purposes, but they are also where deployment credentials leak, so the
 * credential scope keeps them in production scope.
 */
const CI_DEFINITION = [
  /(^|\/)\.github\/workflows\/[^/]+\.ya?ml$/i,
  /(^|\/)\.gitlab-ci\.ya?ml$/i,
  /(^|\/)\.circleci\//i,
  /(^|\/)(?:azure-pipelines|appveyor|bitbucket-pipelines)\.ya?ml$/i,
  /(^|\/)\.buildkite\//i,
];

function normalize(path: string): string {
  return path.replaceAll("\\", "/").replace(/^\.\//, "").toLowerCase();
}

function matchesAny(patterns: RegExp[], value: string): boolean {
  return patterns.some((pattern) => pattern.test(value));
}

function isGeneratedFile(path: string, content: string): boolean {
  if (
    GENERATED_DIRECTORY.test(path) ||
    DEPENDENCY_LOCK_FILE.test(path) ||
    GENERATED_FILE.test(path) ||
    TYPE_DECLARATION_FILE.test(path)
  ) {
    return true;
  }
  if (UI_PRIMITIVE_PATH.test(path) && UI_PRIMITIVE_CONTENT.test(content)) return true;
  return GENERATED_BANNER.test(content.slice(0, GENERATED_BANNER_WINDOW));
}

function isTestFile(path: string, content: string): boolean {
  if (TEST_DIRECTORY.test(path) || matchesAny(TEST_FILE, path)) return true;
  if (matchesAny(NON_PRODUCTION_CONFIGURATION, path)) return true;
  if (matchesAny(TEST_CONTENT, content)) return true;
  return TEST_SUITE_CONTENT.test(content) && TEST_CASE_CONTENT.test(content);
}

/**
 * Classifies one file. `content` is optional: a caller that only holds a path
 * still gets the path-derived role, which is the conservative answer because
 * every content rule can only move a file *away* from `production`.
 */
export function classifyFileRole(path: string, content = ""): FileRole {
  const normalized = normalize(path);
  if (isGeneratedFile(normalized, content)) return "generated";
  if (isTestFile(normalized, content)) return "test";
  if (FIXTURE_DIRECTORY.test(normalized) || matchesAny(FIXTURE_FILE, normalized)) {
    return "fixture";
  }
  if (
    DOCUMENTATION_DIRECTORY.test(normalized) ||
    matchesAny(DOCUMENTATION_FILE, normalized)
  ) {
    return "documentation";
  }
  if (TOOLING_DIRECTORY.test(normalized) || matchesAny(TOOLING_FILE, normalized)) {
    return "tooling";
  }
  return "production";
}

export function isProductionFileRole(role: FileRole): boolean {
  return role === "production";
}

/* ---------------------------------------------------------------------- */
/* Credential scope                                                        */
/* ---------------------------------------------------------------------- */

export type CredentialScope = "production" | "non_production";

/**
 * Credential scope is a narrower question than execution role: *could this
 * value be a deployed credential?*
 *
 * Test code, fixtures, generated artifacts, offline tooling, and documentation
 * declare themselves to be something other than the deployed configuration, so
 * a credential-shaped value inside them is a review signal rather than a
 * production leak. Continuous-integration definitions are the deliberate
 * exception: they are offline tooling for execution purposes, but they hold
 * real deployment credentials, so they stay in production scope.
 */
export function credentialScope(path: string, content = ""): CredentialScope {
  const normalized = normalize(path);
  if (matchesAny(CI_DEFINITION, normalized)) return "production";
  return NON_PRODUCTION_FILE_ROLES.has(classifyFileRole(normalized, content))
    ? "non_production"
    : "production";
}

/* ---------------------------------------------------------------------- */
/* Repository-index helpers                                                */
/* ---------------------------------------------------------------------- */

type IndexedFile = signals.RepositoryIndex["files"][number];

const roleCache = new WeakMap<
  signals.RepositoryIndex,
  Map<string, FileRole>
>();

/** Classifies one indexed file, memoized per repository index. */
export function fileRole(
  index: signals.RepositoryIndex,
  file: IndexedFile,
): FileRole {
  const cache = roleCache.get(index) ?? new Map<string, FileRole>();
  roleCache.set(index, cache);
  const cached = cache.get(file.normalizedPath);
  if (cached) return cached;
  const role = classifyFileRole(file.normalizedPath, file.content);
  cache.set(file.normalizedPath, role);
  return role;
}

/**
 * True when a file is part of the reachable production call graph: real
 * implementation evidence, statically reachable from an application entry
 * point where reachability can be resolved, and classified as production.
 */
export function isProductionExecutionFile(
  index: signals.RepositoryIndex,
  file: IndexedFile,
): boolean {
  return (
    signals.isImplementationEvidencePath(file.path) &&
    signals.isReachableImplementationEvidenceFile(index, file) &&
    isProductionFileRole(fileRole(index, file))
  );
}

/** Every reachable production file in the repository. */
export function productionExecutionFiles(
  index: signals.RepositoryIndex,
): IndexedFile[] {
  return index.files.filter((file) => isProductionExecutionFile(index, file));
}

/* ---------------------------------------------------------------------- */
/* Server execution scope                                                   */
/* ---------------------------------------------------------------------- */

const DEPENDENCY_MANIFEST =
  /(^|\/)(?:package(?:-lock)?\.json|npm-shrinkwrap\.json|composer\.(?:json|lock)|pom\.xml|build\.gradle(?:\.kts)?|requirements\.txt|pyproject\.toml|cargo\.toml|go\.mod|deno\.jsonc?|gemfile)$/i;

const serverExecutionCache = new WeakMap<
  signals.RepositoryIndex,
  ReadonlySet<string>
>();

/**
 * The reachable production call graph of the server.
 *
 * "Does this file run on the server" is a call-graph question, not a filename
 * question. A permission check lives in `src/lib/authz.ts` or
 * `src/middleware/auth.ts` at least as often as it lives inside the route file,
 * and neither of those paths looks like a server surface on its own. Reading
 * only the surface-shaped files silently dropped genuine enforcement.
 *
 * The graph is rooted at every production file that *is* a server surface - a
 * route, an API handler, a serverless function, an Express or framework entry,
 * a JVM or Python module - and then follows their static imports. Browser-only
 * code stays outside it: a module a server root never imports is not server
 * execution, however production-like it looks, so a role branch or a form schema
 * that only the browser evaluates still cannot earn server-side credit.
 */
function serverExecutionPaths(
  index: signals.RepositoryIndex,
): ReadonlySet<string> {
  const cached = serverExecutionCache.get(index);
  if (cached) return cached;

  const production = productionExecutionFiles(index);
  const roots = production.filter(
    (file) =>
      // A manifest declaring `express` is how the static-frontend profile knows
      // a server exists; it is not code the server runs, and a package name is
      // never enforcement evidence.
      !DEPENDENCY_MANIFEST.test(file.normalizedPath) &&
      isServerSurfaceFile(file.normalizedPath, file.content),
  );
  const closure = signals.importClosure(
    index,
    roots.map((file) => file.normalizedPath),
  );
  serverExecutionCache.set(index, closure);
  return closure;
}

/**
 * True when a file is part of the reachable production call graph of the
 * server. This is the scope in which a server-side control - authorization,
 * input validation - may read enforcement evidence.
 */
export function isServerExecutionFile(
  index: signals.RepositoryIndex,
  file: IndexedFile,
): boolean {
  return (
    isProductionExecutionFile(index, file) &&
    serverExecutionPaths(index).has(file.normalizedPath)
  );
}

/** Every reachable production file that the server can execute. */
export function serverExecutionFiles(
  index: signals.RepositoryIndex,
): IndexedFile[] {
  return index.files.filter((file) => isServerExecutionFile(index, file));
}

/**
 * Internal reporting hook. Tests use it to assert that a finding's evidence
 * carries the execution role the control claims to have used. It is never
 * called from the report, contract, or model payload path.
 */
export function evidenceRoles(
  index: signals.RepositoryIndex,
  evidence: readonly EvidenceReference[],
): FileRole[] {
  const byPath = new Map(index.files.map((file) => [file.normalizedPath, file]));
  return evidence.map((reference) => {
    const file = byPath.get(normalize(reference.path));
    return file ? fileRole(index, file) : classifyFileRole(reference.path);
  });
}
